"""
app/assessment/evaluation/answer_evaluator.py

Canonical LLM-backed answer evaluator.

Responsibilities
----------------
- Resolve the requested indicator.
- Build an evaluation prompt.
- Invoke the configured LLM.
- Parse structured LLM output.
- Validate evaluator evidence.
- Return AnswerEvidence.

Non-responsibilities
--------------------
- Goal completion.
- Goal mastery.
- Goal coverage.
- Indicator selection.
- Progression.
- GoalState mutation.
- Persistence.

Important
---------
Each invocation is evaluated independently.

The evaluator does not retain:
- previous questions,
- previous answers,
- previous evaluations,
- previous evidence.

Historical identity is carried explicitly through ``turn_index``,
``question``, ``answer``, and ``request_fingerprint`` on the returned
AnswerEvidence.

The request fingerprint is generated and owned by Python. The LLM
must echo the fingerprint and per-attempt nonce when the strict
identity contract is enabled. Python remains the source of truth.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
import uuid
from dataclasses import dataclass, field
from typing import Any


class AnswerEvaluationError(RuntimeError):
    """Raised when an answer cannot be safely evaluated."""


@dataclass(slots=True)
class AnswerEvidence:
    """
    Canonical evidence for exactly one indicator evaluation.

    ``turn_index``, ``question``, ``answer``, and
    ``request_fingerprint`` identify the historical evaluation that
    produced this evidence.

    These fields are owned by the application rather than inferred
    from LLM output.
    """

    indicator_id: str
    achievement_level: int
    confidence: float
    evidence_strength: float
    indicator_demonstrated: bool
    feedback: str
    rationale: str = ""
    bloom_level: str = ""
    missing_elements: list[str] = field(default_factory=list)
    # Exact excerpts from the learner answer that support the evaluation.
    # These are application-validated grounding anchors, not LLM claims.
    evidence_quotes: list[str] = field(default_factory=list)

    # Historical identity.
    turn_index: int | None = None
    question: str = ""
    answer: str = ""
    request_fingerprint: str = ""

    @property
    def achieved_level(self) -> int:
        """
        Backward-compatible alias.

        New code should use achievement_level.
        """
        return self.achievement_level


@dataclass(slots=True)
class AnswerEvaluator:
    """
    Stateless LLM-backed evaluator for one learner answer.

    Every call to evaluate() is independent of every previous call.
    """

    llm: Any

    MIN_ACHIEVEMENT_LEVEL = 1
    MAX_ACHIEVEMENT_LEVEL = 6
    # Keep the full learner answer for persistence and evidence validation.
    # This is only a guard against pathological prompt construction; ordinary
    # long answers are never silently truncated.
    MAX_EVALUATION_ANSWER_CHARS = 50_000
    MAX_IDENTITY_RETRIES = 2

    def __post_init__(self) -> None:
        if self.llm is None:
            raise ValueError("AnswerEvaluator requires an LLM.")

    # ==========================================================
    # Public API
    # ==========================================================

    def evaluate(
        self,
        *,
        goal: Any,
        indicator_id: str,
        question: str,
        answer: str,
        turn_index: int | None = None,
        assessment_target: dict[str, Any] | None = None,
    ) -> AnswerEvidence:
        """
        Evaluate one answer against exactly one indicator.

        Parameters
        ----------
        goal:
            The goal containing the requested indicator.

        indicator_id:
            Canonical indicator identity. It is never generated by
            the LLM.

        question:
            The exact question presented to the learner.

        answer:
            The exact learner answer being evaluated.

        turn_index:
            Historical conversation-turn identity. It is optional for
            backward compatibility but should be supplied by the
            assessment pipeline.

        Notes
        -----
        The evaluator performs no cross-call state tracking.
        """

        if goal is None:
            raise ValueError("AnswerEvaluator requires a goal.")

        normalized_indicator_id = self._normalize_indicator_id(
            indicator_id
        )

        normalized_question = self._normalize_question(
            question
        )

        normalized_answer = self._normalize_answer(
            answer
        )

        normalized_turn_index = self._normalize_turn_index(
            turn_index
        )

        request_fingerprint = self._request_fingerprint(
            turn_index=normalized_turn_index,
            question=normalized_question,
            answer=normalized_answer,
        )

        indicator = self._resolve_indicator(
            goal=goal,
            indicator_id=normalized_indicator_id,
        )

        last_error: AnswerEvaluationError | None = None

        # A stale provider/model response must never be applied to the
        # current turn.  Each retry gets a fresh nonce in the prompt,
        # while the request fingerprint remains stable for the logical
        # evaluation request.
        for attempt in range(self.MAX_IDENTITY_RETRIES + 1):
            retry_nonce = uuid.uuid4().hex
            if len(normalized_answer) > self.MAX_EVALUATION_ANSWER_CHARS:
                raise AnswerEvaluationError(
                    "Learner answer exceeds the safe evaluation input limit "
                    f"({self.MAX_EVALUATION_ANSWER_CHARS} characters). "
                    "The original answer must be preserved; split or shorten "
                    "the answer before evaluation."
                )

            prompt = self._build_prompt(
                goal=goal,
                indicator=indicator,
                indicator_id=normalized_indicator_id,
                question=normalized_question,
                answer=normalized_answer,
                request_fingerprint=request_fingerprint,
                retry_nonce=retry_nonce,
                assessment_target=assessment_target,
            )
            if attempt > 0:
                prompt += self._retry_instruction(last_error)

            response = self._call_llm(prompt)

            try:
                return self._parse_response(
                    response=response,
                    indicator_id=normalized_indicator_id,
                    indicator=indicator,
                    turn_index=normalized_turn_index,
                    question=normalized_question,
                    answer=normalized_answer,
                    expected_request_fingerprint=request_fingerprint,
                    expected_request_nonce=retry_nonce,
                    require_request_fingerprint=True,
                )
            except AnswerEvaluationError as exc:
                last_error = exc
                if attempt >= self.MAX_IDENTITY_RETRIES:
                    raise AnswerEvaluationError(
                        "Answer evaluation failed after "
                        f"{self.MAX_IDENTITY_RETRIES + 1} attempts: "
                        f"{exc}"
                    ) from exc

        raise AnswerEvaluationError(
            "Answer evaluation failed identity validation."
        ) from last_error

    @staticmethod
    def _retry_instruction(last_error: AnswerEvaluationError | None) -> str:
        """Make retries target the observed failure instead of repeating it."""
        reason = str(last_error or "previous response was not accepted")
        return (
            "\n\nRETRY REQUIREMENT\n"
            "The previous evaluation response was rejected. "
            f"Reason: {reason}\n"
            "Return ONLY one valid JSON object. Do not use Markdown fences. "
            "Do not add commentary before or after the JSON. "
            "Keep feedback and rationale concise. "
            "Copy request_fingerprint and request_nonce exactly. "
            "Any evidence_quotes must be exact excerpts from LEARNER ANSWER.\n"
        )

    # ==========================================================
    # LLM Invocation
    # ==========================================================

    def _call_llm(
        self,
        prompt: str,
    ) -> Any:
        """
        Invoke the configured LLM exactly once for this evaluation.

        The evaluator does not cache or reuse responses.
        """

        messages = [
            {
                "role": "system",
                "content": self._system_prompt(),
            },
            {
                "role": "user",
                "content": prompt,
            },
        ]

        chat_json = getattr(
            self.llm,
            "chat_json",
            None,
        )

        if callable(chat_json):
            try:
                return chat_json(messages)

            except TypeError as exc:
                # Only treat TypeError as a possible signature
                # incompatibility. Actual LLM failures must not be
                # silently swallowed.
                legacy_chat = getattr(
                    self.llm,
                    "chat",
                    None,
                )

                if not callable(legacy_chat):
                    raise AnswerEvaluationError(
                        "LLM chat_json() has an incompatible signature "
                        "and no compatible chat() fallback exists."
                    ) from exc

                try:
                    return legacy_chat(messages)
                except Exception as fallback_exc:
                    raise AnswerEvaluationError(
                        "LLM answer evaluation failed."
                    ) from fallback_exc

            except Exception as exc:
                raise AnswerEvaluationError(
                    "LLM answer evaluation failed."
                ) from exc

        chat = getattr(
            self.llm,
            "chat",
            None,
        )

        if not callable(chat):
            raise AnswerEvaluationError(
                "Configured LLM does not provide chat_json() or chat()."
            )

        try:
            return chat(messages)
        except Exception as exc:
            raise AnswerEvaluationError(
                "LLM answer evaluation failed."
            ) from exc

    # ==========================================================
    # Prompt
    # ==========================================================

    @staticmethod
    def _system_prompt() -> str:
        return (
            "You are an educational assessment evaluator. "
            "Evaluate only the learner's demonstrated understanding "
            "of the specified assessment indicator. "
            "Use only evidence explicitly present in the learner's "
            "answer. "
            "Return a single compact JSON object and nothing else. "
            "Never use Markdown code fences. "
            "Do not include extra keys or explanatory prose outside JSON. "
            "Keep feedback and rationale concise. "
            "Do not infer knowledge from effort, confidence, "
            "politeness, silence, or intent. "
            "Do not award mastery when the answer provides no "
            "substantive evidence for the target indicator. "
            "For substantive positive judgments, every claimed evidence "
            "basis must be grounded in exact excerpts from the learner answer. "
            "Distinguish incorrect, partial, adequate, strong, "
            "and comprehensive understanding. "
            "Return exactly one valid JSON object and no other text."
        )

    def _build_prompt(
        self,
        *,
        goal: Any,
        indicator: Any,
        indicator_id: str,
        question: str,
        answer: str,
        request_fingerprint: str = "",
        retry_nonce: str = "",
        assessment_target: dict[str, Any] | None = None,
    ) -> str:
        goal_name = self._value(
            goal,
            "name",
            "title",
            default="",
        )

        goal_description = self._value(
            goal,
            "description",
            default="",
        )

        indicator_name = self._value(
            indicator,
            "name",
            "title",
            default=indicator_id,
        )

        indicator_description = self._value(
            indicator,
            "description",
            "definition",
            default="",
        )

        bloom_level = self._value(
            indicator,
            "bloom_level",
            default="",
        )

        abet_target_text = "None (use the indicator as the sole assessment target)."
        if assessment_target:
            abet_target_text = (
                f"Outcome: {assessment_target.get('outcome_id','')}\n"
                f"Learning outcome: {assessment_target.get('learning_outcome_id','')}\n"
                f"Criterion: {assessment_target.get('criterion_id','')}\n"
                f"Criterion description: {assessment_target.get('criterion_description','')}"
            )

        return f"""
Evaluate the learner's answer against exactly this assessment
indicator and, when provided, the ABET performance criterion.

GOAL
Name: {goal_name}
Description: {goal_description}

INDICATOR
ID: {indicator_id}
Name: {indicator_name}
Description: {indicator_description}
Bloom level: {bloom_level}

ABET TARGET
{abet_target_text}

QUESTION
{question}

LEARNER ANSWER
{answer}

EVALUATION REQUEST ID
{request_fingerprint}
REQUEST_FINGERPRINT_VALUE: {request_fingerprint}

REQUEST ATTEMPT NONCE
{retry_nonce}
REQUEST_ATTEMPT_NONCE: {retry_nonce}

Rules
-----

1. Evaluate only the learner's actual answer.

2. Use only evidence explicitly present in that answer.

3. Do not infer unstated knowledge.

4. "I don't know", refusal, apology, irrelevant content, or
   unsupported assertions are not evidence of mastery.

5. Distinguish partial understanding from strong understanding.

6. achievement_level must be an integer from 1 through 6.

7. confidence must be between 0.0 and 1.0.

8. evidence_strength must be between 0.0 and 1.0.

9. indicator_demonstrated must be true only when the answer
   substantively demonstrates the target indicator.

10. feedback must be concise and learner-facing.

11. rationale should briefly explain the judgment.

12. missing_elements should list important indicator elements
    absent from the answer.

13. Evidence grounding must come only from LEARNER ANSWER. The
    application, not the model, owns authoritative evidence excerpts.
    Do not invent or rely on evidence that is absent from the answer.

14. evidence_quotes is optional compatibility metadata. If supplied,
    it is non-authoritative and may be ignored by the application.

15. Evaluate only this request. Never reuse a prior turn's evaluation.

16. If the question or answer differs from a previous request,
    recompute the evaluation for the current question and answer.

17. The evaluation request ID is application metadata. Do not
    generate, modify, or rely on it as part of the assessment.

Achievement scale
-----------------

1 = minimal or incorrect evidence
2 = very limited understanding with major gaps
3 = partial understanding with significant gaps
4 = adequate demonstrated understanding
5 = strong demonstrated understanding with minor gaps
6 = comprehensive and highly convincing understanding

Important
---------
achievement_level is an assessment level, not a probability
and not a normalized 0..1 mastery value.

Return exactly:

{{
  "achievement_level": 1,
  "confidence": 0.0,
  "evidence_strength": 0.0,
  "indicator_demonstrated": false,
  "feedback": "string",
  "rationale": "string",
  "missing_elements": [],
  "request_fingerprint": "exact value copied from REQUEST_FINGERPRINT_VALUE",
  "request_nonce": "exact value copied from REQUEST_ATTEMPT_NONCE"
}}
""".strip()

    @staticmethod
    def _request_fingerprint(
        *,
        turn_index: int | None,
        question: str,
        answer: str,
    ) -> str:
        """
        Create a deterministic identity for this evaluation request.

        The fingerprint is generated locally and is never dependent
        on LLM output.
        """

        payload = (
            f"{turn_index}|"
            f"{question.strip()}|"
            f"{answer.strip()}"
        )

        return hashlib.sha256(
            payload.encode("utf-8")
        ).hexdigest()[:24]

    # ==========================================================
    # Indicator Resolution
    # ==========================================================

    @classmethod
    def _resolve_indicator(
        cls,
        *,
        goal: Any,
        indicator_id: str,
    ) -> Any:
        get_indicator = getattr(
            goal,
            "get_indicator",
            None,
        )

        if callable(get_indicator):
            try:
                indicator = get_indicator(indicator_id)
            except (
                KeyError,
                LookupError,
            ):
                indicator = None

            if indicator is not None:
                return indicator

        indicators = getattr(
            goal,
            "indicators",
            None,
        )

        if isinstance(indicators, dict):
            indicator = indicators.get(indicator_id)

            if indicator is not None:
                return indicator

        if isinstance(indicators, (list, tuple)):
            for candidate in indicators:
                candidate_id = (
                    getattr(
                        candidate,
                        "id",
                        None,
                    )
                    or getattr(
                        candidate,
                        "indicator_id",
                        None,
                    )
                )

                if candidate_id is None:
                    continue

                normalized_candidate_id = cls._normalize_indicator_id(
                    candidate_id,
                    allow_empty=True,
                )

                if normalized_candidate_id == indicator_id:
                    return candidate

        indicator_states = getattr(
            goal,
            "indicator_states",
            None,
        )

        if isinstance(indicator_states, dict):
            indicator = indicator_states.get(indicator_id)

            if indicator is not None:
                return indicator

        raise ValueError(
            f"Unknown indicator '{indicator_id}'."
        )

    # ==========================================================
    # Response Parsing
    # ==========================================================

    def _parse_response(
        self,
        *,
        response: Any,
        indicator_id: str,
        indicator: Any,
        turn_index: int | None = None,
        question: str = "",
        answer: str = "",
        expected_request_fingerprint: str = "",
        expected_request_nonce: str = "",
        require_request_fingerprint: bool = False,
    ) -> AnswerEvidence:
        """
        Parse and validate the LLM assessment.

        Historical identity is attached by Python after parsing.
        The LLM is not trusted to supply application identity.
        """

        data = self._coerce_response_to_dict(response)

        achievement_level = self._achievement_level(data)

        confidence = self._probability(
            data,
            "confidence",
        )

        evidence_strength = self._probability(
            data,
            "evidence_strength",
        )

        demonstrated = self._boolean(
            data,
            "indicator_demonstrated",
        )

        feedback = self._string(
            data,
            "feedback",
        )

        rationale = self._string(
            data,
            "rationale",
            required=False,
        )

        missing_elements = self._string_list(
            data,
            "missing_elements",
        )

        # Evidence excerpts are application-owned. Never trust the LLM
        # to author authoritative evidence spans: provider formatting,
        # punctuation, or paraphrasing can otherwise turn a valid
        # evaluation into a retry/failure.
        evidence_quotes = self._extract_evidence_quotes(
            answer=answer,
            question=question,
            indicator=indicator,
        )

        # ------------------------------------------------------
        # Optional compatibility check
        #
        # If an LLM/provider happens to return a fingerprint,
        # validate it. But do NOT require the LLM to return one.
        # Python remains the source of truth.
        # ------------------------------------------------------

        response_fingerprint = data.get(
            "request_fingerprint"
        )

        if response_fingerprint is None:
            if require_request_fingerprint:
                raise AnswerEvaluationError(
                    "LLM response is missing the required "
                    "request_fingerprint."
                )
        else:
            if not isinstance(
                response_fingerprint,
                str,
            ):
                response_fingerprint = str(
                    response_fingerprint
                )

            response_fingerprint = response_fingerprint.strip()

            if (
                expected_request_fingerprint
                and response_fingerprint
                != expected_request_fingerprint
            ):
                raise AnswerEvaluationError(
                    "LLM response fingerprint does not match "
                    "the current evaluation request."
                )

        response_nonce = data.get("request_nonce")
        if response_nonce is None:
            if require_request_fingerprint:
                raise AnswerEvaluationError(
                    "LLM response is missing the required "
                    "request_nonce."
                )
        else:
            if not isinstance(response_nonce, str):
                response_nonce = str(response_nonce)
            response_nonce = response_nonce.strip()
            if expected_request_nonce and response_nonce != expected_request_nonce:
                raise AnswerEvaluationError(
                    "LLM response nonce does not match the current "
                    "evaluation attempt."
                )

        # ------------------------------------------------------
        # Application-owned identity
        # ------------------------------------------------------

        application_fingerprint = (
            expected_request_fingerprint
            or self._request_fingerprint(
                turn_index=turn_index,
                question=question,
                answer=answer,
            )
        )

        bloom_level = self._value(
            indicator,
            "bloom_level",
            default="",
        ).strip()

        (
            achievement_level,
            demonstrated,
            evidence_strength,
            feedback,
            rationale,
            missing_elements,
        ) = self._apply_non_demonstration_guard(
            answer=answer,
            achievement_level=achievement_level,
            demonstrated=demonstrated,
            evidence_strength=evidence_strength,
            feedback=feedback,
            rationale=rationale,
            missing_elements=missing_elements,
        )

        return AnswerEvidence(
            indicator_id=indicator_id,
            achievement_level=achievement_level,
            confidence=confidence,
            evidence_strength=evidence_strength,
            indicator_demonstrated=demonstrated,
            feedback=feedback,
            rationale=rationale,
            bloom_level=bloom_level,
            missing_elements=missing_elements,
            evidence_quotes=evidence_quotes,

            # Application-owned historical identity.
            turn_index=turn_index,
            question=question,
            answer=answer,
            request_fingerprint=application_fingerprint,
        )

    @classmethod
    def _apply_non_demonstration_guard(
        cls,
        *,
        answer: str,
        achievement_level: int,
        demonstrated: bool,
        evidence_strength: float,
        feedback: str,
        rationale: str,
        missing_elements: list[str],
    ) -> tuple[int, bool, float, str, str, list[str]]:
        """Prevent high positive outcomes for explicit no-evidence answers.

        This is a narrow deterministic safety boundary. It does not judge
        correctness and does not override substantive answers; it only blocks
        a model from awarding demonstrated mastery when the learner explicitly
        provides no answer/evidence.
        """
        normalized = re.sub(r"\s+", " ", str(answer or "")).strip().casefold()
        if not normalized:
            return (
                min(achievement_level, 1),
                False,
                0.0,
                "The answer does not provide evidence for the target indicator.",
                "The learner did not provide substantive evidence to assess.",
                missing_elements,
            )

        refusal_only = bool(re.fullmatch(
            r"(?:i\s+don['’]?t\s+know|idk|no\s+idea|not\s+sure|i\s+am\s+not\s+sure|"
            r"cannot\s+answer|can['’]?t\s+answer|no\s+answer|pass|skip)[.!]?",
            normalized,
        ))

        if not refusal_only:
            return (
                achievement_level,
                demonstrated,
                evidence_strength,
                feedback,
                rationale,
                missing_elements,
            )

        guarded_missing = list(missing_elements)
        if not guarded_missing:
            guarded_missing = ["Substantive evidence for the target indicator."]

        return (
            min(achievement_level, 2),
            False,
            min(evidence_strength, 0.10),
            "The answer does not provide evidence for the target indicator.",
            "The learner explicitly indicated that they could not provide an answer, so mastery cannot be inferred.",
            guarded_missing,
        )


    @classmethod
    def _extract_evidence_quotes(
        cls,
        *,
        answer: str,
        question: str = "",
        indicator: Any = None,
        rationale: str = "",
        feedback: str = "",
    ) -> list[str]:
        """Extract exact evidence spans from the learner answer locally.

        The LLM may judge the answer, but it never owns the evidence text.
        Every returned quote is a direct slice of ``answer`` and therefore
        cannot be fabricated by the evaluator.
        """
        text = str(answer or "").strip()
        if not text:
            return []

        # Preserve exact source text while using lightweight normalized
        # tokens only for relevance scoring. This also works for code answers.
        chunks = [c.strip() for c in re.split(r"\n\s*\n+|(?<=[.!?])\s+", text) if c.strip()]
        if not chunks:
            chunks = [text]

        indicator_name = cls._value(
            indicator,
            "name",
            "title",
            default="",
        )
        indicator_description = cls._value(
            indicator,
            "description",
            "definition",
            default="",
        )

        # Ground quote selection only in immutable assessment inputs.
        # Evaluator-generated rationale/feedback are intentionally excluded
        # so hallucinated model prose cannot influence which learner text is
        # treated as supporting evidence.
        context = cls._normalize_evidence_text(
            " ".join((question, indicator_name, indicator_description))
        )
        context_tokens = {
            token for token in re.findall(r"[a-z0-9_]{3,}", context)
            if token not in {"the", "and", "that", "with", "this", "from", "for", "are", "you", "your"}
        }

        scored: list[tuple[int, int, str]] = []
        for index, chunk in enumerate(chunks):
            normalized = cls._normalize_evidence_text(chunk)
            tokens = set(re.findall(r"[a-z0-9_]{3,}", normalized))
            score = len(tokens & context_tokens)
            # Prefer substantive answer material, but keep deterministic order.
            if len(normalized) >= 20:
                score += 1
            scored.append((score, -index, chunk))

        scored.sort(reverse=True)
        quotes: list[str] = []
        seen: set[str] = set()
        total = 0
        for _, _, chunk in scored:
            # Keep source text exact; cap each excerpt without inventing text.
            quote = chunk[:500].strip()
            if not quote:
                continue
            key = cls._normalize_evidence_text(quote)
            if not key or key in seen:
                continue
            if total + len(quote) > 1500:
                remaining = 1500 - total
                if remaining < 20:
                    break
                quote = quote[:remaining].rstrip()
                key = cls._normalize_evidence_text(quote)
                if not key:
                    break
            seen.add(key)
            quotes.append(quote)
            total += len(quote)
            if len(quotes) >= 5 or total >= 1500:
                break

        return quotes

    @classmethod
    def _evidence_quotes(
        cls,
        data: dict[str, Any],
        *,
        answer: str,
        achievement_level: int,
        indicator_demonstrated: bool,
    ) -> list[str]:
        """Backward-compatible wrapper using application-owned extraction.

        ``data`` is intentionally ignored so LLM-generated quote text can
        never become authoritative evidence.
        """
        return cls._extract_evidence_quotes(answer=answer)

    @staticmethod
    def _normalize_evidence_text(value: str) -> str:
        """Normalize whitespace for robust exact-substring verification."""
        return re.sub(r"\s+", " ", str(value or "")).strip().casefold()

    @classmethod
    def _coerce_response_to_dict(
        cls,
        response: Any,
    ) -> dict[str, Any]:
        if isinstance(response, dict):
            return response

        text = str(response or "").strip()

        if not text:
            raise AnswerEvaluationError(
                "Answer evaluator returned an empty response."
            )

        data = cls._extract_json(text)

        if not isinstance(data, dict):
            raise AnswerEvaluationError(
                "Answer evaluator response must be a JSON object."
            )

        return data

    # ==========================================================
    # JSON
    # ==========================================================

    @staticmethod
    def _extract_json(
        text: str,
    ) -> Any:
        """Parse JSON while tolerating common provider wrappers."""
        candidates = [text.strip()]

        fenced = re.sub(
            r"^\s*```(?:json)?\s*",
            "",
            text,
            flags=re.IGNORECASE,
        )
        fenced = re.sub(r"\s*```\s*$", "", fenced).strip()
        if fenced and fenced not in candidates:
            candidates.append(fenced)

        # Use JSONDecoder.raw_decode so a valid object followed by stray
        # provider text is still recoverable. Unlike first/last-brace
        # slicing, this does not get confused by braces inside strings.
        decoder = json.JSONDecoder()
        for candidate in candidates:
            try:
                value, _ = decoder.raw_decode(candidate)
                return value
            except json.JSONDecodeError:
                pass

            for match in re.finditer(r"\{", candidate):
                try:
                    value, _ = decoder.raw_decode(candidate[match.start():])
                    return value
                except json.JSONDecodeError:
                    continue

        raise AnswerEvaluationError(
            "Answer evaluator returned invalid JSON. "
            f"Provider response length={len(text)} characters."
        )

    # ==========================================================
    # Achievement
    # ==========================================================

    @classmethod
    def _achievement_level(
        cls,
        data: dict[str, Any],
    ) -> int:
        value = data.get("achievement_level")

        if value is None:
            value = data.get("achieved_level")

        if value is None:
            raise AnswerEvaluationError(
                "'achievement_level' is required."
            )

        if isinstance(value, bool):
            raise AnswerEvaluationError(
                "'achievement_level' must be numeric."
            )

        try:
            number = float(value)
        except (
            TypeError,
            ValueError,
        ) as exc:
            raise AnswerEvaluationError(
                "'achievement_level' must be numeric."
            ) from exc

        if not math.isfinite(number):
            raise AnswerEvaluationError(
                "'achievement_level' must be finite."
            )

        if number != int(number):
            raise AnswerEvaluationError(
                "'achievement_level' must be an integer from 1 to 6."
            )

        normalized = int(number)

        if not (
            cls.MIN_ACHIEVEMENT_LEVEL
            <= normalized
            <= cls.MAX_ACHIEVEMENT_LEVEL
        ):
            raise AnswerEvaluationError(
                "'achievement_level' must be between 1 and 6."
            )

        return normalized

    # ==========================================================
    # Probability
    # ==========================================================

    @staticmethod
    def _probability(
        data: dict[str, Any],
        name: str,
    ) -> float:
        value = data.get(name)

        if value is None:
            raise AnswerEvaluationError(
                f"'{name}' is required."
            )

        if isinstance(value, bool):
            raise AnswerEvaluationError(
                f"'{name}' must be numeric."
            )

        try:
            number = float(value)
        except (
            TypeError,
            ValueError,
        ) as exc:
            raise AnswerEvaluationError(
                f"'{name}' must be numeric."
            ) from exc

        if not math.isfinite(number):
            raise AnswerEvaluationError(
                f"'{name}' must be finite."
            )

        if not 0.0 <= number <= 1.0:
            raise AnswerEvaluationError(
                f"'{name}' must be between 0.0 and 1.0."
            )

        return number

    # ==========================================================
    # Boolean
    # ==========================================================

    @staticmethod
    def _boolean(
        data: dict[str, Any],
        name: str,
    ) -> bool:
        value = data.get(name)

        if isinstance(value, bool):
            return value

        if isinstance(value, str):
            normalized = value.strip().lower()

            if normalized in {
                "true",
                "yes",
                "1",
            }:
                return True

            if normalized in {
                "false",
                "no",
                "0",
            }:
                return False

        raise AnswerEvaluationError(
            f"'{name}' must be boolean."
        )

    # ==========================================================
    # Strings
    # ==========================================================

    @staticmethod
    def _string(
        data: dict[str, Any],
        name: str,
        *,
        required: bool = True,
    ) -> str:
        value = data.get(name)

        if value is None:
            if required:
                raise AnswerEvaluationError(
                    f"'{name}' is required."
                )

            return ""

        if not isinstance(value, str):
            value = str(value)

        normalized = value.strip()

        if required and not normalized:
            raise AnswerEvaluationError(
                f"'{name}' must not be empty."
            )

        return normalized

    @classmethod
    def _string_list(
        cls,
        data: dict[str, Any],
        name: str,
    ) -> list[str]:
        value = data.get(name, [])

        if value is None:
            return []

        if isinstance(value, str):
            normalized = value.strip()

            return [normalized] if normalized else []

        if isinstance(value, (list, tuple)):
            result: list[str] = []

            for item in value:
                normalized = str(item).strip()

                if normalized:
                    result.append(normalized)

            return result

        raise AnswerEvaluationError(
            f"'{name}' must be a list of strings."
        )

    # ==========================================================
    # Generic Values
    # ==========================================================

    @staticmethod
    def _value(
        obj: Any,
        *names: str,
        default: str = "",
    ) -> str:
        for name in names:
            if isinstance(obj, dict) and name in obj:
                value = obj[name]

                if value is not None:
                    return str(value)

            value = getattr(
                obj,
                name,
                None,
            )

            if value is not None:
                return str(value)

        return default

    # ==========================================================
    # Normalization
    # ==========================================================

    @staticmethod
    def _normalize_indicator_id(
        indicator_id: Any,
        *,
        allow_empty: bool = False,
    ) -> str | None:
        if indicator_id is None:
            if allow_empty:
                return None

            raise ValueError(
                "indicator_id is required."
            )

        value = str(indicator_id).strip()

        if not value:
            if allow_empty:
                return None

            raise ValueError(
                "indicator_id is required."
            )

        return value

    @staticmethod
    def _normalize_answer(
        answer: Any,
    ) -> str:
        value = str(answer or "").strip()

        if not value:
            raise ValueError(
                "Interview answer cannot be empty."
            )

        return value

    @staticmethod
    def _normalize_question(
        question: Any,
    ) -> str:
        value = str(question or "").strip()

        if not value:
            raise ValueError(
                "Interview question cannot be empty."
            )

        return value

    @staticmethod
    def _normalize_turn_index(
        turn_index: Any,
    ) -> int | None:
        if turn_index is None:
            return None

        if isinstance(turn_index, bool):
            raise ValueError(
                "turn_index must be an integer."
            )

        try:
            normalized = int(turn_index)
        except (
            TypeError,
            ValueError,
        ) as exc:
            raise ValueError(
                "turn_index must be an integer."
            ) from exc

        if normalized < 1:
            raise ValueError(
                "turn_index must be >= 1."
            )

        return normalized
